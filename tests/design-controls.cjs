/* Geometry and keyboard regression for the rendered, local design prototype.
 * Usage: node tests/design-controls.cjs /absolute/path/to/rendered-preview.html
 * No CRM server, credentials, or business data are used.
 */
const assert = require('node:assert/strict');
const path = require('node:path');
const {pathToFileURL} = require('node:url');
const {chromium} = require('playwright');

async function checkSelects(app, context) {
  const selects = await app.locator('select:visible').evaluateAll(nodes => nodes.map(select => {
    const style = getComputedStyle(select), rect = select.getBoundingClientRect();
    const arrow = select.parentElement.querySelector('[data-lucide="chevron-down"]');
    const icon = arrow?.getBoundingClientRect();
    const canvas = document.createElement('canvas').getContext('2d');
    canvas.font = `${style.fontWeight} ${style.fontSize} ${style.fontFamily}`;
    return {
      name: select.getAttribute('aria-label') || 'Тестовий товар', appearance: style.appearance,
      padding: parseFloat(style.paddingRight), pointer: arrow && getComputedStyle(arrow).pointerEvents,
      centerError: icon ? Math.abs((rect.top + rect.bottom - icon.top - icon.bottom) / 2) : null,
      rightGap: icon ? rect.right - icon.right : null, iconWidth: icon?.width,
      textWidth: canvas.measureText(select.selectedOptions[0].textContent).width,
      textRoom: rect.width - parseFloat(style.paddingLeft) - parseFloat(style.paddingRight) - 2,
      sample: select.hasAttribute('data-item'), height: rect.height,
      native: select instanceof HTMLSelectElement, named: Boolean(select.labels.length || select.getAttribute('aria-label'))
    };
  }));
  assert(selects.length, `${context}: visible selects`);
  for (const select of selects) {
    const message = `${context}: ${select.name}`;
    assert(select.native && select.named, `${message}: semantics and accessible name`);
    assert.equal(select.appearance, 'none', `${message}: native arrow disabled`);
    assert.equal(select.pointer, 'none', `${message}: arrow must not intercept clicks`);
    assert.equal(select.padding, 40, `${message}: reserved text gutter`);
    assert.equal(select.iconWidth, 16, `${message}: visible icon size`);
    assert(select.centerError < 1, `${message}: vertical center`);
    assert(Math.abs(select.rightGap - 12) < 1, `${message}: right inset`);
    if (!select.sample) assert(select.textWidth <= select.textRoom + 1, `${message}: short value clipped`);
  }
}

(async () => {
  assert(process.argv[2], 'Pass the standalone preview generated by visualize/scripts/render.py');
  const browser = await chromium.launch({ headless: true });
  try {
    for (const touch of [false, true]) {
      const context = await browser.newContext({hasTouch: touch, viewport: {width: 1024, height: 2200}});
      const page = await context.newPage(), errors = [];
      page.on('pageerror', error => errors.push(error.message));
      await page.goto(pathToFileURL(path.resolve(process.argv[2])).href, {waitUntil: 'domcontentloaded'});
      const frame = page.frames().find(candidate => candidate !== page.mainFrame());
      await frame.waitForSelector('.pd-desk .pd-table');
      await frame.waitForSelector('.pd-desk .pd-select-box svg');
      for (const theme of ['light', 'dark']) for (const width of touch ? [320] : [1024, 736, 390, 320]) {
        await page.setViewportSize({width, height: 2200});
        await page.emulateMedia({colorScheme: theme});
        for (const [variant, key] of [['Робочий простір', 'desk'], ['Торговий портал', 'retail']]) {
          await frame.locator('.viz-carousel-picker summary').click();
          await frame.locator('.viz-carousel-options button').filter({hasText: variant}).click();
          const app = frame.locator(`[data-app=${key}]`), label = `${key}/${theme}/${width}/${touch ? 'touch' : 'mouse'}`;
          await app.locator('[data-page=catalog]:visible').first().click();
          await checkSelects(app, label);
          const heights = await app.locator('.pd-toolbar').evaluate(toolbar => [...toolbar.querySelectorAll('input,select')].map(node => node.getBoundingClientRect().height));
          assert(Math.abs(heights[0] - heights[1]) < 1, `${label}: search/filter height`);
          await app.locator('[data-search]').focus();
          await page.keyboard.press('Tab');
          assert(await app.locator('[data-filter]').evaluate(node => document.activeElement === node), `${label}: native keyboard tab order`);
          const focus = await app.locator('[data-filter]').evaluate(node => getComputedStyle(node).outlineStyle);
          assert.notEqual(focus, 'none', `${label}: visible keyboard focus`);
          // Mac headless Chrome does not expose its OS-native select popup to
          // keyboard automation. Exercise the native change event separately.
          await app.locator('[data-filter]').selectOption('promo');
          assert.equal(await app.locator('.pd-product-name').count(), 1);
          assert(await app.locator('[data-filter]').evaluate(node => document.activeElement === node), `${label}: focus survives redraw`);
          await app.locator('[data-filter]').selectOption('all');
          if (width === 1024 && !touch) await app.screenshot({path: `/tmp/tsukenya-controls-${key}-${theme}.png`});
          await app.locator('[data-page=labels]:visible').first().click();
          await app.locator('[data-font]').selectOption('Georgia');
          await checkSelects(app, label);
          const toolbarHeights = await app.locator('.pd-context-tools').evaluate(toolbar => [...toolbar.querySelectorAll('select,input,button')].map(node => node.getBoundingClientRect().height));
          assert(toolbarHeights.every(height => height === (touch ? 44 : 32)), `${label}: compact control height ${toolbarHeights}`);
          await app.locator('[data-font]').selectOption('Arial');
          if (touch) assert(await app.locator('[data-bold]').evaluate(node => node.getBoundingClientRect().width >= 44), `${label}: touch button width`);
          assert(await frame.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `${label}: overflow`);
          if (width === 320) await app.screenshot({path: `/tmp/tsukenya-controls-${key}-${theme}-${touch ? 'touch' : 'mobile'}.png`});
          await page.emulateMedia({colorScheme: theme, forcedColors: 'active'});
          assert(await app.locator('select').evaluateAll(nodes => nodes.every(node => getComputedStyle(node).appearance === 'auto' && getComputedStyle(node.parentElement.querySelector('[data-lucide="chevron-down"]')).display === 'none')), `${label}: high contrast native fallback`);
          await page.emulateMedia({colorScheme: theme, forcedColors: 'none'});
        }
      }
      assert.deepEqual(errors, []);
      await context.close();
    }
    console.log('PASS: arrow geometry, text gutter, keyboard Tab/focus, control heights, touch targets, high contrast; 2 variants, 2 themes, 4 widths. Native OS popup selection needs a visible-browser check.');
  } finally { await browser.close(); }
})().catch(error => {console.error(error); process.exitCode = 1;});
