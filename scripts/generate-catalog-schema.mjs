import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const schema=JSON.parse(fs.readFileSync(path.join(root,'contracts/catalog-exchange.schema.json'),'utf8'));
const output='/* Generated by scripts/generate-catalog-schema.mjs; edit the registry. */\n'+
`(() => { const schema=${JSON.stringify(schema)};
 const normal=value=>String(value??'').replace(/\\s+/g,' ').trim().toLocaleLowerCase('uk-UA').replace(/[.,:;()№]/g,' ').replace(/\\s+/g,' ').trim();
 const field=key=>schema.fields.find(f=>f.key===key);
 const columns=(profile,privateFields=true)=>schema.profiles[profile].keys.map(field).filter(f=>privateFields||!f.private).map(f=>({...f,label:schema.profiles[profile].labels?.[f.key]||f.label}));
 function mapping(headers){
  const raw=headers.map(value=>String(value??'').trim());
  const markers=raw.flatMap((header,index)=>[...header.matchAll(/ \\[Каталог TSukenya (\\d+)\\]/g)].map(match=>({index,version:match[1]})));
  if(markers.length>1)throw Error('Повторена позначка схеми каталогу. Залиште лише одну.');
  if(markers.length&&markers[0].version!=='1')throw Error('Версія схеми каталогу не підтримується. Оновіть застосунок.');
  const canonical=markers.length===1;
  if(canonical){const index=markers[0].index;if(!raw[index].endsWith(schema.marker))throw Error('Позначка схеми має стояти наприкінці заголовка.');raw[index]=raw[index].slice(0,-schema.marker.length);}
  const names=raw.map(normal),result={},readonly=[];
  for(let i=0;i<names.length;i++){
   if(!names[i])continue;
   const exact=schema.fields.find(f=>normal(f.label)===names[i]);
   const matched=exact||schema.fields.find(f=>f.writable&&f.aliases.some(pattern=>new RegExp(pattern).test(names[i])));
   if(!matched)continue;if(!matched.writable){readonly.push(raw[i]);continue;}
   if(Object.hasOwn(result,matched.key))throw Error('Повторений стовпець «'+matched.label+'». Залиште лише один.');
   result[matched.key]=i;
  }
  if(result.cost===undefined&&result.price===undefined){const generic=names.findIndex(h=>['ціна','ціна грн'].includes(h));if(generic>=0)result.generic=generic;}
  return {columns:result,readonly,canonical};
 }
 const api={...schema,field,columns,mapping};if(typeof module!=='undefined'&&module.exports)module.exports=api;else globalThis.CatalogSchema=api;
})();\n`;
const table='# Поля схеми каталогу 1\n\n'+
 'Згенеровано з `contracts/catalog-exchange.schema.json`; редагуйте registry, потім `node scripts/generate-catalog-schema.mjs`.\n\n'+
 '| Поле | Поточний заголовок | Роль у файлі | Формат |\n| --- | --- | --- | --- |\n'+
 schema.fields.map(f=>'| `'+f.key+'` | '+f.label+' | '+(f.key==='id'?'Селектор оновлення':f.writable?'Редагування':'Лише перегляд')+(f.private?'; приватне':'')+' | '+f.kind+(f.scale===undefined?'':' ('+f.scale+' знаки)')+(f.unit==='percentage_points'?'; процентні пункти':'')+' |').join('\n')+'\n\n'+
 '| Профіль | Полів | Призначення |\n| --- | --- | --- |\n'+
 Object.entries(schema.profiles).map(([key,p])=>'| `'+key+'` | '+p.keys.length+' | '+p.description+' |').join('\n')+'\n\n'+
 'Касовий export пропускає приватні поля: '+schema.profiles.export.keys.filter(key=>!schema.fields.find(f=>f.key===key).private).length+' стовпців. Перша назва поточних файлів містить `'+schema.marker.trim()+'`.\n';
const outputs=[['app/catalog-schema.js',output],['docs/CATALOG-SCHEMA-FIELDS.md',table]];
for(const [relative,value] of outputs){
 const target=path.join(root,relative);
 if(process.argv.includes('--check')){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==value)throw Error(relative+' differs from registry; regenerate');}
 else fs.writeFileSync(target,value);
}
